"""Plot full-test-window comparisons for foundation-model predictions.

The foundation predictions are expected to have been generated by
``scripts/run_foundation_models.py`` and stored under each archive's
``predictions/`` directory.  This script deliberately does not rerun model
inference; it validates the saved full-test arrays and creates the same style
of selected 500-step comparison figure used for the trained models.
"""

from __future__ import annotations

import argparse
import pickle
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


REPO_ROOT = Path(__file__).resolve().parents[1]
MODEL_FILES = (
    ("chronos2", "Chronos-2 (0-shot)", "#1f77b4", "-"),
    ("timesfm", "TimesFM (0-shot)", "#ff7f0e", "--"),
    ("tirex2_univariate", "TiRex-2 (0-shot)", "#2ca02c", "-."),
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", required=True)
    parser.add_argument("--mode", choices=("manoeuvre", "navigation"), required=True)
    parser.add_argument(
        "--output-dir",
        default="outputs/figures/paper",
        help="Directory for the generated figure files.",
    )
    parser.add_argument("--segment-length", type=int, default=500)
    parser.add_argument("--formats", default="eps,png")
    parser.add_argument("--dpi", type=int, default=400)
    return parser.parse_args()


def inverse_target(values: np.ndarray, metadata: dict) -> np.ndarray:
    target_names = list(metadata["targetNames"])
    if len(target_names) != 1:
        raise ValueError(f"Expected one target, got {target_names}")
    mean = float(metadata["MU"].loc[target_names[0]])
    scale = float(metadata["SIG"].loc[target_names[0]])
    return np.asarray(values, dtype=np.float64) * scale + mean


def load_full_test_data(archive: Path):
    with np.load(archive / "windows.npz", allow_pickle=False) as windows:
        Xte = np.asarray(windows["Xte"], dtype=np.float32)
        Yte = np.asarray(windows["Yte"], dtype=np.float32)
    with (archive / "scalers_and_meta.pkl").open("rb") as handle:
        metadata = pickle.load(handle)

    if Xte.ndim != 3 or Yte.ndim != 3 or len(Xte) != len(Yte):
        raise ValueError(f"Invalid test-window shapes: Xte={Xte.shape}, Yte={Yte.shape}")
    y_true = inverse_target(Yte, metadata)[:, 0, 0]
    predictions = {}
    for key, label, color, linestyle in MODEL_FILES:
        prediction_path = archive / "predictions" / f"{key}.npz"
        if not prediction_path.is_file():
            raise FileNotFoundError(prediction_path)
        with np.load(prediction_path, allow_pickle=False) as saved:
            prediction = np.asarray(saved["yhat_test_phys"])
        expected = (len(Xte), Yte.shape[1], 1)
        if prediction.shape != expected:
            raise ValueError(
                f"{prediction_path}: expected {expected}, got {prediction.shape}"
            )
        predictions[label] = (prediction[:, 0, 0], color, linestyle)
    return Xte, y_true, predictions


def main() -> int:
    args = parse_args()
    archive = Path(args.archive)
    if not archive.is_absolute():
        archive = REPO_ROOT / archive
    output_dir = Path(args.output_dir)
    if not output_dir.is_absolute():
        output_dir = REPO_ROOT / output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    if args.segment_length < 1 or args.dpi < 1:
        raise ValueError("segment length and dpi must be positive")

    Xte, y_true, predictions = load_full_test_data(archive)
    length = min(args.segment_length, len(y_true))
    max_start = len(y_true) - length
    starts = np.unique(np.linspace(0, max_start, num=min(20, max_start + 1), dtype=int))
    best_start = 0
    best_score = -np.inf
    for start in starts:
        segment = y_true[start : start + length]
        score = float(np.ptp(segment)) if args.mode == "manoeuvre" else float(np.std(segment))
        if score > best_score:
            best_start, best_score = int(start), score

    time = Xte.shape[1] + best_start + np.arange(length)
    plt.rcParams.update({
        "font.family": "serif",
        "font.size": 10.5,
        "axes.titlesize": 11,
        "axes.labelsize": 10,
        "xtick.labelsize": 9.5,
        "ytick.labelsize": 9.5,
        "legend.fontsize": 9,
    })
    figure, axis = plt.subplots(figsize=(6.5, 2.8))
    axis.plot(
        time,
        y_true[best_start : best_start + length],
        color="black",
        linewidth=1.8,
        label="Measured",
        zorder=10,
    )
    for label, (prediction, color, linestyle) in predictions.items():
        axis.plot(
            time,
            prediction[best_start : best_start + length],
            color=color,
            linestyle=linestyle,
            linewidth=1.0,
            label=label,
            zorder=5,
        )
    axis.set_xlabel("Time (s)")
    axis.set_ylabel("Active power (pu)")
    axis.legend(fontsize=8.5, frameon=True, ncol=2, loc="upper right")
    axis.grid(True)
    figure.tight_layout()

    stem = f"models_comparison_full_test_foundation_{'man' if args.mode == 'manoeuvre' else 'nav'}"
    formats = tuple(value.strip().lower() for value in args.formats.split(",") if value.strip())
    unsupported = set(formats) - {"eps", "png", "pdf"}
    if not formats or unsupported:
        raise ValueError(f"Unsupported formats: {sorted(unsupported)}")
    for figure_format in formats:
        path = output_dir / f"{stem}.{figure_format}"
        figure.savefig(path, dpi=args.dpi, bbox_inches="tight")
        print(f"Figure saved: {path}")
    plt.close(figure)
    print(f"Validated full test windows: N={len(Xte)}, segment_start={best_start}, segment_length={length}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
